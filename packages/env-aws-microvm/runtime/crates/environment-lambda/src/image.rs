/// Packs the build context: image recipe, boot/runner scripts, and the aarch64 guest binary.
/// Deterministic: fixed entry order, fixed timestamps — the same inputs give byte-identical
/// ZIPs, so the S3 key (content hash) is stable across rebuilds.
pub fn pack_zip(guest_binary: &[u8]) -> anyhow::Result<Vec<u8>> {
    let mut zw = zip::ZipWriter::new(std::io::Cursor::new(Vec::new()));
    let file = |mode: u32| {
        zip::write::SimpleFileOptions::default()
            .compression_method(zip::CompressionMethod::Deflated)
            .last_modified_time(zip_time())
            .unix_permissions(mode)
    };
    zw.start_file("Dockerfile", file(0o644))?;
    zw.write_all(dockerfile().as_bytes())?;
    zw.start_file("environment-boot.sh", file(0o755))?;
    zw.write_all(boot_script().as_bytes())?;
    zw.start_file("environment-guest", file(0o755))?;
    zw.write_all(guest_binary)?;
    zw.start_file("tool-runner.mjs", file(0o644))?;
    zw.write_all(include_bytes!("../../../image/tool-runner.mjs"))?;
    zw.start_file("tool-boundary.c", file(0o644))?;
    zw.write_all(include_bytes!("../../../image/tool-boundary.c"))?;
    zw.start_file("proc-secret-static.c", file(0o644))?;
    zw.write_all(include_bytes!("../../../image/proc-secret-static.c"))?;
    zw.start_file("control-listener.c", file(0o644))?;
    zw.write_all(include_bytes!("../../../image/control-listener.c"))?;
    Ok(zw.finish()?.into_inner())
}

/// Where a packed context lives in the artifact bucket.
#[must_use]
pub fn artifact_key(zip: &[u8]) -> String {
    let sha = hex::encode(sha2::Sha256::digest(zip));
    format!("environments/images/{sha}.zip")
}

/// Everything `publish` needs besides the bytes.
#[derive(Debug, Clone)]
pub struct PublishConfig {
    /// Exact lowercase 40-hex source commit represented by this publication.
    pub source_sha: String,
    /// Image name (one per shape variant), e.g. `environments-dev-1gb`.
    pub name: String,
    /// S3 bucket the ZIP is uploaded to.
    pub bucket: String,
    /// IAM role the build assumes to read the ZIP.
    pub build_role_arn: String,
    /// CloudWatch log group for build output.
    pub log_group: String,
    /// Exact plane-owned connector ARNs accepted by the release. `RunMicrovm` selects one sealed
    /// class for each generation; the image build itself uses one AWS-managed connector.
    pub egress_connectors: Vec<String>,
}

/// The published outcome: what `RunMicrovm` needs.
#[derive(Debug, Clone)]
pub struct PublishedImage {
    pub image_arn: String,
    pub image_version: String,
}

/// Bump this whenever a fixed `CreateMicrovmImage`/`UpdateMicrovmImage` request field changes.
/// Variable request fields are hashed individually below.
const PUBLISH_REQUEST_TOKEN_SCHEMA: &str = "environment-lambda-publish-request-v5";

#[derive(Clone, Copy)]
enum PublishOperation {
    Create,
    Update,
}

impl PublishOperation {
    const fn as_str(self) -> &'static str {
        match self {
            Self::Create => "create",
            Self::Update => "update",
        }
    }
}

/// AWS treats a client token as an idempotency key for the complete API request, not merely the
/// uploaded bytes. Hash every variable request identity field and the validated runtime connector
/// policy with unambiguous length prefixes. The schema marker represents the fixed fields (hooks,
/// ARM64, image-build internet egress, and capabilities). The client token and the resume
/// fingerprint are the same digest over different identity prefixes, so they cannot drift apart.
fn publish_request_digest(identity: &[&str], cfg: &PublishConfig, artifact_key: &str) -> String {
    let mut digest = sha2::Sha256::new();
    for field in [PUBLISH_REQUEST_TOKEN_SCHEMA]
        .into_iter()
        .chain(identity.iter().copied())
        .chain([
            cfg.source_sha.as_str(),
            cfg.name.as_str(),
            cfg.bucket.as_str(),
            cfg.build_role_arn.as_str(),
            cfg.log_group.as_str(),
            artifact_key,
        ])
    {
        digest.update((field.len() as u64).to_be_bytes());
        digest.update(field.as_bytes());
    }
    let mut connectors = cfg.egress_connectors.clone();
    connectors.sort();
    for connector in connectors {
        digest.update((connector.len() as u64).to_be_bytes());
        digest.update(connector.as_bytes());
    }
    hex::encode(&digest.finalize()[..16])
}

fn publish_client_token(
    operation: PublishOperation,
    region: &str,
    image_identifier: &str,
    cfg: &PublishConfig,
    artifact_key: &str,
) -> String {
    publish_request_digest(
        &[operation.as_str(), region, image_identifier],
        cfg,
        artifact_key,
    )
}

fn publish_request_fingerprint(region: &str, cfg: &PublishConfig, artifact_key: &str) -> String {
    publish_request_digest(&[region], cfg, artifact_key)
}

pub fn validate_source_sha(source_sha: &str) -> anyhow::Result<()> {
    anyhow::ensure!(
        source_sha.len() == 40
            && source_sha
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte)),
        "source SHA must be exactly 40 lowercase hexadecimal characters"
    );
    Ok(())
}

fn publish_description(source_sha: &str, request_fingerprint: &str) -> String {
    format!(
        "Aex Environment source {source_sha} request {request_fingerprint} ({MVP_TARGET_MEMORY_MIB} MiB shape)"
    )
}

pub fn validate_network_connector_arn(connector: &str, region: &str) -> anyhow::Result<()> {
    let mut parts = connector.split(':');
    let fixed = ["arn", "aws", "lambda", region];
    for expected in fixed {
        anyhow::ensure!(
            parts.next() == Some(expected),
            "invalid network connector ARN"
        );
    }
    let account = parts.next().unwrap_or_default();
    anyhow::ensure!(
        account.len() == 12 && account.bytes().all(|byte| byte.is_ascii_digit()),
        "invalid network connector ARN"
    );
    anyhow::ensure!(
        parts.next() == Some("network-connector"),
        "invalid network connector ARN"
    );
    let name = parts.next().unwrap_or_default();
    anyhow::ensure!(
        !name.is_empty()
            && name.len() <= 64
            && name
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_')),
        "invalid network connector ARN"
    );
    if let Some(version) = parts.next() {
        anyhow::ensure!(
            !version.is_empty()
                && version.bytes().all(|byte| byte.is_ascii_digit())
                && version != "0",
            "invalid network connector ARN"
        );
    }
    anyhow::ensure!(parts.next().is_none(), "invalid network connector ARN");
    Ok(())
}

fn validated_connectors(connectors: &[String], region: &str) -> anyhow::Result<Vec<String>> {
    let mut connectors = connectors.to_vec();
    connectors.sort();
    connectors.dedup();
    anyhow::ensure!(
        connectors.len() == 3,
        "image publication requires three distinct plane-owned egress connector ARNs"
    );
    for connector in &connectors {
        validate_network_connector_arn(connector, region)?;
    }
    Ok(connectors)
}

fn image_build_egress_connector(region: &str) -> String {
    format!("arn:aws:lambda:{region}:aws:network-connector:aws-network-connector:INTERNET_EGRESS")
}

/// Uploads the context and registers a new image (or a new version of an existing one), then
/// waits for AWS's build to finish. Idempotent by exact publish request: the client token includes
/// the artifact digest and all plane-specific request identity.
pub async fn publish(
    control: &Control,
    s3: &aws_sdk_s3::Client,
    cfg: &PublishConfig,
    zip: Vec<u8>,
) -> anyhow::Result<PublishedImage> {
    validate_source_sha(&cfg.source_sha)?;
    validated_connectors(&cfg.egress_connectors, control.region())?;
    let key = artifact_key(&zip);
    let request_fingerprint = publish_request_fingerprint(control.region(), cfg, &key);
    let description = publish_description(&cfg.source_sha, &request_fingerprint);
    let existing_arn = find_image_arn(control, &cfg.name).await?;

    if let Some(arn) = existing_arn.as_deref()
        && let Some(version) = resumable_version(control, arn, &description).await?
    {
        tracing::info!(%arn, source_sha = %cfg.source_sha, "resuming existing source publication");
        return wait_for_build(control, arn, &version, &description).await;
    }

    let uri = upload_context(s3, cfg, &key, zip).await?;
    let (arn, version) =
        register_image(control, existing_arn, cfg, &description, uri, &key).await?;
    tracing::info!(%arn, %version, "image registration accepted; AWS is building");
    wait_for_build(control, &arn, &version, &description).await
}

/// The newest version whose description carries this exact request fingerprint, if any.
async fn resumable_version(
    control: &Control,
    arn: &str,
    description: &str,
) -> anyhow::Result<Option<String>> {
    let versions = control
        .sdk()
        .list_microvm_image_versions()
        .image_identifier(arn)
        .send()
        .await
        .map_err(|e| anyhow::Error::new(read_error(&e)).context("list_microvm_image_versions"))?;
    Ok(versions
        .items()
        .iter()
        .max_by_key(|version| version_ord(version.image_version()))
        .filter(|version| version.description() == Some(description))
        .map(|version| version.image_version().to_owned()))
}

async fn upload_context(
    s3: &aws_sdk_s3::Client,
    cfg: &PublishConfig,
    key: &str,
    zip: Vec<u8>,
) -> anyhow::Result<String> {
    let uri = format!("s3://{}/{key}", cfg.bucket);
    s3.put_object()
        .bucket(&cfg.bucket)
        .key(key)
        .body(aws_sdk_s3::primitives::ByteStream::from(zip))
        .send()
        .await
        .context("uploading image context to S3")?;
    tracing::info!(%uri, "context uploaded");
    Ok(uri)
}

fn publish_hooks() -> Hooks {
    Hooks::builder()
        .port(i32::from(AGENT_PORT))
        .microvm_hooks(
            MicrovmHooks::builder()
                .run(HookState::Enabled)
                .run_timeout_in_seconds(60)
                // These hook requests carry no application authentication and arrive on the
                // guest-visible listener. Resume needs no mutation; shutdown is external; and
                // sandbox persistence is never implicit.
                .resume(HookState::Disabled)
                .suspend(HookState::Disabled)
                .terminate(HookState::Disabled)
                .build(),
        )
        .microvm_image_hooks(
            MicrovmImageHooks::builder()
                .ready(HookState::Enabled)
                .ready_timeout_in_seconds(300)
                .validate(HookState::Enabled)
                .validate_timeout_in_seconds(120)
                .build(),
        )
        .build()
}

/// Registers a new image or a new version of an existing one. The shared request field list is
/// written once inside the macro, so create and update cannot drift apart.
async fn register_image(
    control: &Control,
    existing_arn: Option<String>,
    cfg: &PublishConfig,
    description: &str,
    uri: String,
    key: &str,
) -> anyhow::Result<(String, String)> {
    let logging = Logging::CloudWatch(
        CloudWatchLogging::builder()
            .log_group(&cfg.log_group)
            .log_stream(&cfg.name)
            .build(),
    );
    let cpu = CpuConfiguration::builder()
        .architecture(Architecture::Arm64)
        .build()
        .context("cpu configuration")?;
    let resources = Resources::builder()
        .minimum_memory_in_mib(MVP_TARGET_MEMORY_MIB as i32)
        .build()
        .context("resources")?;
    macro_rules! with_image_spec {
        ($builder:expr, $client_token:expr) => {
            $builder
                .base_image_arn(base_image_arn(control.region()))
                .build_role_arn(&cfg.build_role_arn)
                .description(description)
                .code_artifact(CodeArtifact::Uri(uri))
                .logging(logging)
                .egress_network_connectors(image_build_egress_connector(control.region()))
                .cpu_configurations(cpu)
                .resources(resources)
                .additional_os_capabilities(Capability::All)
                .hooks(publish_hooks())
                .client_token($client_token)
                .send()
                .await
        };
    }
    let sdk = control.sdk();
    if let Some(arn) = existing_arn {
        let client_token =
            publish_client_token(PublishOperation::Update, control.region(), &arn, cfg, key);
        let out = with_image_spec!(
            sdk.update_microvm_image().image_identifier(&arn),
            &client_token
        )
        .map_err(|e| anyhow::Error::new(read_error(&e)).context("update_microvm_image"))?;
        Ok((out.image_arn().to_owned(), out.image_version().to_owned()))
    } else {
        let client_token = publish_client_token(
            PublishOperation::Create,
            control.region(),
            &cfg.name,
            cfg,
            key,
        );
        let out = with_image_spec!(sdk.create_microvm_image().name(&cfg.name), &client_token)
            .map_err(|e| anyhow::Error::new(read_error(&e)).context("create_microvm_image"))?;
        Ok((out.image_arn().to_owned(), out.image_version().to_owned()))
    }
}

/// Polls until the exact accepted version leaves PENDING/IN_PROGRESS. AWS's builds run minutes,
/// not seconds; the timeout is generous and the caller sees every transition.
pub async fn wait_for_build(
    control: &Control,
    image_arn: &str,
    image_version: &str,
    expected_description: &str,
) -> anyhow::Result<PublishedImage> {
    let deadline = tokio::time::Instant::now() + Duration::from_secs(30 * 60);
    let sdk = control.sdk();
    loop {
        let version = match sdk
            .get_microvm_image_version()
            .image_identifier(image_arn)
            .image_version(image_version)
            .send()
            .await
            .map_err(|e| read_error(&e))
        {
            Ok(version) => version,
            // A transient read failure must not abort a build that AWS is still running.
            Err(ControlError::Retryable(cause) | ControlError::Throttled(cause)) => {
                tracing::debug!(%cause, "image build state read deferred");
                anyhow::ensure!(
                    tokio::time::Instant::now() <= deadline,
                    "image build did not finish within 30 minutes"
                );
                tokio::time::sleep(Duration::from_secs(15)).await;
                continue;
            }
            Err(error) => {
                return Err(anyhow::Error::new(error).context("get_microvm_image_version"));
            }
        };
        anyhow::ensure!(
            version.description() == Some(expected_description),
            "accepted image version does not match the requested source publication"
        );
        match version.state() {
            MicrovmImageVersionState::Successful => {
                tracing::info!(%image_version, "image version built");
                return Ok(PublishedImage {
                    image_arn: image_arn.to_owned(),
                    image_version: image_version.to_owned(),
                });
            }
            MicrovmImageVersionState::Failed => {
                bail!(
                    "image version {image_version} failed: {}",
                    version.state_reason().unwrap_or("no reason given")
                );
            }
            state => {
                tracing::info!(%image_version, ?state, "building…");
            }
        }
        if tokio::time::Instant::now() > deadline {
            bail!("image build did not finish within 30 minutes");
        }
        tokio::time::sleep(Duration::from_secs(15)).await;
    }
}

/// Whether the image version needs rebuilding: its recorded MicroVM base version is no longer
/// the newest managed base version (AWS retires old bases on its own schedule).
pub async fn rebuild_due(
    control: &Control,
    image_arn: &str,
    image_version: &str,
) -> anyhow::Result<Option<String>> {
    let sdk = control.sdk();
    let ours = sdk
        .get_microvm_image_version()
        .image_identifier(image_arn)
        .image_version(image_version)
        .send()
        .await
        .map_err(|e| anyhow::Error::new(read_error(&e)).context("get_microvm_image_version"))?;
    let base_arn = ours.base_image_arn().to_owned();
    let our_base = ours.base_image_version().unwrap_or("0").to_owned();
    let managed = sdk
        .list_managed_microvm_image_versions()
        .image_identifier(&base_arn)
        .send()
        .await
        .map_err(|e| {
            anyhow::Error::new(read_error(&e)).context("list_managed_microvm_image_versions")
        })?;
    let newest = managed
        .items()
        .iter()
        .map(|v| v.image_version().to_owned())
        .max_by_key(|v| version_ord(v));
    match newest {
        Some(newest) if version_ord(&newest) > version_ord(&our_base) => Ok(Some(newest)),
        _ => Ok(None),
    }
}

/// Orders version strings like `3.0` numerically, not lexically (so `10.0` > `9.0`).
fn version_ord(v: &str) -> (u64, u64) {
    let mut parts = v.split('.');
    let major = parts.next().and_then(|p| p.parse().ok()).unwrap_or(0);
    let minor = parts.next().and_then(|p| p.parse().ok()).unwrap_or(0);
    (major, minor)
}

/// Rejects any guest binary that is not an aarch64 ELF before packing: the MicroVM image is
/// ARM64-only, and a wrong-architecture binary would fail only inside AWS's build minutes later.
pub fn validate_aarch64_elf(bytes: &[u8]) -> anyhow::Result<()> {
    const ELF_MAGIC: [u8; 4] = [0x7f, b'E', b'L', b'F'];
    const EM_AARCH64: u8 = 0xb7;
    anyhow::ensure!(
        bytes.len() > 19 && bytes[..4] == ELF_MAGIC && bytes[18] == EM_AARCH64,
        "guest binary is not an aarch64 ELF"
    );
    Ok(())
}

/// One printable row per registered version of an image.
pub struct VersionSummary {
    pub version: String,
    pub state: String,
    pub status: String,
    pub base_version: String,
}

pub async fn version_summaries(
    control: &Control,
    image_arn: &str,
) -> anyhow::Result<Vec<VersionSummary>> {
    let versions = control
        .sdk()
        .list_microvm_image_versions()
        .image_identifier(image_arn)
        .send()
        .await
        .map_err(|e| anyhow::Error::new(read_error(&e)).context("list_microvm_image_versions"))?;
    Ok(versions
        .items()
        .iter()
        .map(|version| VersionSummary {
            version: version.image_version().to_owned(),
            state: format!("{:?}", version.state()),
            status: format!("{:?}", version.status()),
            base_version: version.base_image_version().unwrap_or("?").to_owned(),
        })
        .collect())
}

/// The ARN of the image named `name`, if it exists. Accepts an ARN and returns it unchanged.
pub async fn find_image_arn(control: &Control, name: &str) -> anyhow::Result<Option<String>> {
    if name.starts_with("arn:") {
        return Ok(Some(name.to_owned()));
    }
    let mut next: Option<String> = None;
    loop {
        let out = control
            .sdk()
            .list_microvm_images()
            .set_next_token(next)
            .send()
            .await
            .map_err(|e| anyhow::Error::new(read_error(&e)).context("list_microvm_images"))?;
        for item in out.items() {
            if item.name() == name {
                return Ok(Some(item.image_arn().to_owned()));
            }
        }
        next = out.next_token().map(str::to_owned);
        if next.is_none() {
            return Ok(None);
        }
    }
}

