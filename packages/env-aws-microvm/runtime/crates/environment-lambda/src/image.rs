/// The container base, pinned by digest (resolved from public ECR on 2026-08-18). A tag is a
/// moving reference; a digest is the bytes. Public ECR rather than Docker Hub because the AWS
/// build environment pulls anonymously and Docker Hub throttles anonymous pulls from AWS IPs.
pub const CONTAINER_BASE: &str = "public.ecr.aws/ubuntu/ubuntu:24.04@sha256:a54764b5b6340c272ffb45e303fe4c8064bbdfb76d732b325b79ae6b92900e4c";

/// The JavaScript runtime used by deployable Brain tools. The MicroVM image is ARM64-only, so
/// its archive digest can be pinned directly. Keep the plain-Docker image's ARM64 pin in sync.
pub const NODE_VERSION: &str = "22.23.2";
pub const NODE_ARM64_SHA256: &str =
    "fff4078c5def658577f92c88db7db3bc0072924bfb93fe52c1e744a54e94abb8";
/// Patched npm replacing the vulnerable copy bundled with the pinned Node archive.
pub const NPM_VERSION: &str = "11.19.0";

/// The Lambda-managed MicroVM base every image must sit on.
pub fn base_image_arn(region: &str) -> String {
    format!("arn:aws:lambda:{region}:aws:microvm-image:al2023-1")
}

/// Fixed ZIP entry timestamp (2026-08-01T00:00:00Z) so the artifact digest is a function of
/// its contents, not of the build clock.
fn zip_time() -> zip::DateTime {
    zip::DateTime::from_date_and_time(2026, 8, 1, 0, 0, 0).expect("valid constant timestamp")
}

/// The in-guest DNS resolver. The MicroVM blocks outbound UDP, which breaks ordinary
/// resolv.conf entries; this AWS-provided address answers inside the VM.
pub const GUEST_DNS: &str = "169.254.169.253";

/// Default swap: 2 GiB, created and enabled at boot so memory pressure turns "job failed" into
/// "job was slow". Boot continues if `swapon` is refused; the swap probe records the outcome.
pub const DEFAULT_SWAP_BYTES: u64 = 2 * 1024 * 1024 * 1024;
/// The only hosted alpha MicroVM shape. Capacity accounting in the production Environment consumes this
/// same constant, so image publication cannot expose an operator-selected physical memory size.
pub const MVP_TARGET_MEMORY_MIB: u32 = 1_024;

/// The boot script: root sets up DNS and swap, then a root-owned launcher binds the reserved
/// provider port and drops to the dedicated Environment supervisor before exec. The launcher transfers
/// only kill/setuid/setgid process capabilities. The supervisor irreversibly drops Tool children
/// to `agent`; arbitrary code never shares the control UID. `CAP_KILL` is required because Linux
/// does not grant a parent a special right to signal a child after that child changes to UID 1000.
#[must_use]
pub fn boot_script() -> String {
    format!(
        r#"#!/bin/sh
# Generated by environment-lambda. Runs as root, drops to the Environment supervisor.
set -eu
printf 'nameserver {GUEST_DNS}\n' > /etc/resolv.conf || true
# Reserve the provider's fixed listener port. The root-owned launcher binds it before dropping to
# the supervisor; a background Tool cannot bind it after a crash. Tool access to a live listener
# is independently rejected by its generation-scoped bearer.
unprivileged_port_start=$(( {AGENT_PORT} + 1 ))
if [ "$(cat /proc/sys/net/ipv4/ip_unprivileged_port_start)" != "$unprivileged_port_start" ]; then
  printf '%s\n' "$unprivileged_port_start" > /proc/sys/net/ipv4/ip_unprivileged_port_start
fi
test "$(cat /proc/sys/net/ipv4/ip_unprivileged_port_start)" = "$unprivileged_port_start"
if [ -w /proc/sys/kernel/unprivileged_userns_clone ]; then
  printf '0\n' > /proc/sys/kernel/unprivileged_userns_clone
fi
if [ -w /proc/sys/user/max_user_namespaces ]; then
  printf '0\n' > /proc/sys/user/max_user_namespaces
fi
ulimit -c 0
# Engine-created workspace directories and ordinary Tool output share the workspace group. An
# explicit mode-0600 file remains binding-private until its owner deliberately changes the mode.
umask 0002
swap_bytes="${{ENVIRONMENT_SWAP_BYTES:-{DEFAULT_SWAP_BYTES}}}"
if [ "$swap_bytes" -gt 0 ] 2>/dev/null; then
  if [ ! -f /swapfile ]; then
    fallocate -l "$swap_bytes" /swapfile 2>/dev/null \
      || dd if=/dev/zero of=/swapfile bs=1M count=$((swap_bytes / 1048576)) 2>/dev/null || true
    chmod 600 /swapfile 2>/dev/null || true
    mkswap /swapfile >/dev/null 2>&1 || true
  fi
  swapon /swapfile 2>&1 || echo "aex-boot: swapon failed" >&2
fi
exec /usr/local/lib/environment/control-listener /usr/local/bin/environment-guest
"#
    )
}

